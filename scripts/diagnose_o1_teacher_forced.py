"""Compare O1 policy chunks with expert actions at real expert observations.

This diagnostic never steps the environment with policy actions.  Training
observations come from the saved staging episodes; held-out observations are
generated by the scripted expert in the same simulation checkout.
"""

from __future__ import annotations

import argparse
import functools
import json
from pathlib import Path

import numpy as np
import websockets.sync.client

from mj_env.adapters import LeRobotSO101Adapter
from mj_env.scripts.scripted_pick import GraspSolver
from mj_env.scripts.scripted_pick_place import run_pick_place
from mj_env.task_env import TaskEnv


PROMPT = "put the red cube on the blue disc"


def training_episode(root: Path, seed: int) -> dict[str, np.ndarray]:
    manifest = [json.loads(line) for line in (root / "manifest.jsonl").read_text().splitlines()]
    record = next(item for item in manifest if item["seed"] == seed)
    if record["task"] != PROMPT or not record["success"]:
        raise ValueError(f"unexpected training record for seed {seed}: {record}")
    with np.load(root / record["path"], allow_pickle=False) as episode:
        arrays = {key: np.asarray(episode[key]) for key in ("image", "wrist_image", "state", "actions")}
    return arrays


def heldout_episode(seed: int) -> dict[str, np.ndarray]:
    env = TaskEnv("o1_open_baseline", max_episode_steps=10_000)
    adapter = LeRobotSO101Adapter(env)
    frames: dict[str, list[np.ndarray]] = {key: [] for key in ("image", "wrist_image", "state", "actions")}

    def on_frame(action: np.ndarray, observation: dict, info: dict) -> None:
        del info
        frames["image"].append(np.asarray(observation["observation.image"]).copy())
        frames["wrist_image"].append(np.asarray(observation["observation.wrist_image"]).copy())
        frames["state"].append(adapter.to_lerobot(observation["observation.state"]))
        frames["actions"].append(adapter.to_lerobot(action))

    try:
        outcome = run_pick_place(
            env, GraspSolver(env.model), seed=seed, instruction=PROMPT, on_frame=on_frame
        )
    finally:
        env.close()
    if not outcome["success"]:
        raise RuntimeError(f"held-out expert failed seed {seed}: {outcome}")
    return {key: np.stack(value) for key, value in frames.items()}


def phase_indices(actions: np.ndarray) -> dict[str, int]:
    gripper = actions[:, 5]
    # The jaw may start very wide and move towards the pre-grasp aperture for
    # 30-50 frames.  That is not the contact-closing phase.  The true grip is
    # the later transition from ~33 motor units to the minimum (~22).
    search_start = min(50, max(0, len(gripper) - 10))
    minimum = float(np.min(gripper[search_start : max(search_start + 1, int(len(gripper) * 0.75))]))
    near_grip = np.flatnonzero(gripper[search_start:] <= minimum + 8.0)
    if len(near_grip) == 0:
        raise ValueError("no gripper-contact phase found")
    closing = search_start + int(near_grip[0])
    return {
        "start": 0,
        "before_close": max(0, closing - 5),
        "closing": min(len(actions) - 5, closing + 5),
        "carry": min(len(actions) - 5, closing + 35),
    }


def compare(client, group: str, seed: int, episode: dict[str, np.ndarray], repeats: int) -> list[dict]:
    actions = episode["actions"]
    rows = []
    for phase, index in phase_indices(actions).items():
        if index + 5 > len(actions):
            continue
        request = {
            "observation/image": episode["image"][index],
            "observation/wrist_image": episode["wrist_image"][index],
            "observation/state": episode["state"][index],
            "prompt": PROMPT,
        }
        predicted = np.stack([
            np.asarray(client.infer(request)["actions"], dtype=np.float32)[:5, :6]
            for _ in range(repeats)
        ])
        expert = actions[index : index + 5]
        if predicted.shape != (repeats, 5, 6) or not np.isfinite(predicted).all():
            raise ValueError(f"invalid predicted actions {predicted.shape}")
        diff = predicted - expert[None]
        row = {
            "group": group,
            "seed": seed,
            "phase": phase,
            "frame": index,
            "expert_gripper_5": np.round(expert[:, 5], 2).tolist(),
            "pred_gripper_5_mean": np.round(predicted[:, :, 5].mean(axis=0), 2).tolist(),
            "pred_gripper_5_std": np.round(predicted[:, :, 5].std(axis=0), 2).tolist(),
            "arm_mae_motor": round(float(np.mean(np.abs(diff[:, :, :5]))), 3),
            "gripper_mae_motor": round(float(np.mean(np.abs(diff[:, :, 5]))), 3),
            "arm_step0_abs_error": np.round(np.mean(np.abs(diff[:, 0, :5]), axis=0), 2).tolist(),
            "state_motor": np.round(episode["state"][index], 2).tolist(),
        }
        print(json.dumps(row), flush=True)
        rows.append(row)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--training-root", type=Path, required=True)
    parser.add_argument("--train-seeds", type=int, nargs="+", default=[10000, 10001])
    parser.add_argument("--heldout-seeds", type=int, nargs="+", default=[20001, 20012])
    parser.add_argument("--port", type=int, default=8000)
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    websockets.sync.client.connect = functools.partial(websockets.sync.client.connect, ping_interval=None)
    from openpi_client import websocket_client_policy

    client = websocket_client_policy.WebsocketClientPolicy(port=args.port)
    rows = []
    for seed in args.train_seeds:
        rows.extend(compare(client, "train", seed, training_episode(args.training_root, seed), args.repeats))
    for seed in args.heldout_seeds:
        rows.extend(compare(client, "heldout", seed, heldout_episode(seed), args.repeats))
    args.output.write_text("\n".join(json.dumps(row) for row in rows) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
